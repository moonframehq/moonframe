#!/usr/bin/env python3
"""Generate both browsers from the actual pattern definitions and preview mods."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "patterns/app"


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def field(source, key):
    match = re.search(r'^\t' + key + r' = ("(?:[^"\\]|\\.)*")', source, re.M)
    if not match:
        raise ValueError(f"Missing {key}")
    return json.loads(match[1])


def catalog():
    result = []
    for preview in sorted((APP / "mods").glob("preview-*/main.luau")):
        name = preview.parent.name.removeprefix("preview-")
        source = (APP / "components" / f"{name}.luau").read_text()
        parts = re.findall(r'\buse "([a-z0-9-]+)"', source)
        for part in parts:
            if not (ROOT / "app/components" / f"{part}.luau").is_file():
                raise ValueError(f"{name}: dependency {part} is not a built-in component")
        result.append(dict(id=name, **{key: field(source, key) for key in
                           ("title", "category", "icon", "description", "when")},
                           parts=parts, source=source, example=preview.read_text()))
    return result


def native(entries):
    # Strings are one line each, so the generated file stays small in lines;
    # the UI lives in pattern-browser, not a second template in this exporter.
    rows = []
    for entry in entries:
        fields = [f"\t\t{key} = {quote(value)}," for key, value in entry.items() if key != "parts"]
        fields.append("\t\tparts = { " + ", ".join(map(quote, entry["parts"])) + " },")
        rows.append("\t{\n" + "\n".join(fields) + "\n\t},")
    return '''-- Generated by scripts/patterns-data.py; edit the pattern or its preview.
local browser = use "pattern-browser"
local ENTRIES = {
''' + "\n".join(rows) + '''
}
return mod {
    init = function() return { category = "All patterns", query = "", code = "example" } end,
    update = function(state: any, msg)
        if msg == "back" then state.selected = nil
        elseif type(msg) == "table" then
            if msg.msg == "query" then state.query = msg.value; state.selected = nil
            elseif msg.category then state.category = msg.category; state.selected = nil
            elseif msg.select then state.selected = msg.select
            elseif msg.code then state.code = msg.code end
        end
    end,
    view = function(state) return browser { entries = ENTRIES, state = state } end,
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    entries = catalog()
    outputs = {
        APP / "mods/catalog/main.luau": native(entries),
        ROOT / "website/site/docs/patterns/data.js": "// Generated by scripts/patterns-data.py\nwindow.PATTERNS = " + json.dumps(entries, ensure_ascii=False) + ";\n",
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale: {path.relative_to(ROOT)}; run python3 scripts/patterns-data.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"ok: {len(entries)} patterns, native and website catalogs")


if __name__ == "__main__":
    main()
