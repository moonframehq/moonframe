#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["Markdown==3.8.2"]
# ///
"""Render the WASM guide from its Markdown source into the static docs site.

Run: uv run website/tools/wasm-guide.py [--check]
The docs introduction supplies the shared layout, navigation and search.
No server-side build is needed; commit the generated page with the source.
"""

import argparse
import html
import re
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/wasm-providers.md"
TEMPLATE = ROOT / "website/site/docs/index.html"
OUTPUT = ROOT / "website/site/docs/wasm-providers/index.html"
URL = "https://docs.moonframe.dev/wasm-providers/"
RAW = "https://raw.githubusercontent.com/moonframehq/moonframe/main/docs/wasm-providers.md"
TITLE = "Building WebAssembly (WASM) providers"
DESCRIPTION = (
    "Build a Moonframe WebAssembly (WASM) provider in Rust: a complete component, "
    "Luau messages, live reload, capabilities, validation and packaging. For humans and agents."
)


def render():
    template = TEMPLATE.read_text()
    md = markdown.Markdown(extensions=["fenced_code", "tables", "toc"])
    body = md.convert(SOURCE.read_text())
    # The page's title is already visible; the right rail lists its sections.
    toc = "".join(
        f'<a href="#{html.escape(item["id"])}">{item["name"]}</a>'
        for item in md.toc_tokens[0]["children"]
    )
    style = re.search(r"<style>.*?</style>", template, re.S).group()
    header = re.search(r'<header class="top".*?</header>', template, re.S).group()
    sidebar = re.search(r'<aside id="side">.*?</aside>', template, re.S).group()
    sidebar = sidebar.replace('class="on" href="/"', 'href="https://docs.moonframe.dev/"')
    sidebar = sidebar.replace(f'href="{URL}"', f'class="on" href="{URL}"')
    # Introduction anchors belong to that page, not this guide.
    sidebar = sidebar.replace('href="#', 'href="https://docs.moonframe.dev/#')
    header = header.replace('href="/"', 'href="https://docs.moonframe.dev/"')
    script = re.search(r"<script>.*?</script>", template, re.S).group()
    return f"""<!doctype html>
<!-- Generated by website/tools/wasm-guide.py from docs/wasm-providers.md. -->
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{TITLE} · Moonframe docs</title>
<meta name="description" content="{DESCRIPTION}">
<link rel="canonical" href="{URL}">
<link rel="alternate" type="text/markdown" title="Guide as Markdown" href="{RAW}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="Moonframe">
<meta property="og:title" content="{TITLE}">
<meta property="og:description" content="{DESCRIPTION}">
<meta property="og:url" content="{URL}">
{style}
<style>
  main {{ min-width:0 }}
  main a {{ text-decoration:underline; text-underline-offset:3px }}
  main a:hover {{ color:var(--acc) }}
  main ul, main ol {{ padding-left:24px; margin:14px 0 22px; color:var(--ink2) }}
  main li {{ margin:8px 0 }}
  pre code {{ font:inherit; background:none; padding:0 }}
  td code {{ overflow-wrap:anywhere }}
  .toc {{ max-height:calc(100vh - 58px); overflow:auto }}
</style>
<body>
{header}
<div class="layout">
{sidebar}
<main>
<p class="crumb">Building blocks · WebAssembly (WASM)</p>
<p><a href="{RAW}">Read as Markdown</a> · For people and coding agents</p>
{body}
</main>
<nav class="toc" aria-label="On this page"><b>On this page</b>{toc}
<div class="edit"><a href="https://github.com/moonframehq/moonframe/edit/main/docs/wasm-providers.md">Edit this guide ↗</a></div>
</nav>
</div>
{script}
</body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated page is stale")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != page:
            raise SystemExit("WASM guide is stale: uv run website/tools/wasm-guide.py")
        print("WASM guide is up to date")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(page)
        print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
