//! Renders every component's demo on Rune and reports how each fared.
//! `MOONFRAME_RUNE_COVERAGE=file` writes the table there:
//! `MOONFRAME_RUNE_COVERAGE=$PWD/docs/rune-coverage.md cargo test -p moonframe-rune coverage`.

#![allow(clippy::expect_used, clippy::unwrap_used)]

use {
    super::*,
    rune::{Env, Runtime},
    std::{
        collections::BTreeSet,
        fmt::Write as _,
        panic::{AssertUnwindSafe, catch_unwind},
        path::Path,
    },
};

/// How one component's demo went.
#[derive(PartialEq)]
enum Fared {
    Draws,
    /// Draws, with these elements as markers.
    Partly(BTreeSet<String>),
    /// Its demo reports this, on any renderer's account.
    Problem(String),
    /// Nothing but the browser's own list and stage was drawn.
    Empty,
    /// Drawing it panicked.
    Panicked(String),
}

fn fared(window: &mut Runtime<Ui>, name: &str) -> Fared {
    window.state.left_out.get_mut().clear();
    let drawn = catch_unwind(AssertUnwindSafe(|| {
        window.update(|ui, _| ui.preview = Some(name.to_owned()));
        for _ in 0..3 {
            window.frame(1. / 60.);
        }
    }));
    if let Err(panic) = drawn {
        let message = panic
            .downcast_ref::<String>()
            .cloned()
            .or_else(|| panic.downcast_ref::<&str>().map(|text| (*text).to_owned()))
            .unwrap_or_default();
        return Fared::Panicked(message);
    }
    // Without a demo the page draws the component's `example`.
    if let Some(error) = window
        .state
        .workspace()
        .demo(name)
        .and_then(|(_, slot)| slot.error())
    {
        return Fared::Problem(error.to_string());
    }
    let elements = window.elements();
    let stage = elements
        .iter()
        .position(|element| element.key.as_deref() == Some("gallery-stage"));
    let drew = stage.is_some_and(|stage| {
        elements
            .iter()
            .any(|element| element.parent == Some(stage) && element.rect[2] * element.rect[3] > 0.)
    });
    if !drew {
        return Fared::Empty;
    }
    let left_out = window.state.left_out.get_mut();
    if left_out.is_empty() {
        Fared::Draws
    } else {
        Fared::Partly(left_out.clone())
    }
}

#[test]
fn every_component_draws_or_says_what_it_lacks() {
    let app = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app");
    let mut ui = Ui::open(app, None);
    ui.gallery = true;
    ui.waker = Some(Arc::new(|| {}));
    ui.workspace_mut().show_demos(true);
    let names: Vec<(String, String)> = ui
        .workspace()
        .components()
        .iter()
        .map(|component| (component.name.clone(), component.category.clone()))
        .collect();
    let mut window = Runtime::new(ui, view, (1000., 800.), Env::new(true, 2.));
    let results: Vec<(String, String, Fared)> = names
        .into_iter()
        .map(|(name, category)| {
            let result = fared(&mut window, &name);
            (name, category, result)
        })
        .collect();

    let count = |test: fn(&Fared) -> bool| results.iter().filter(|(.., fared)| test(fared)).count();
    let draws = count(|fared| *fared == Fared::Draws);
    let partly = count(|fared| matches!(fared, Fared::Partly(_)));
    let problem = count(|fared| matches!(fared, Fared::Problem(_)));
    let panicked = count(|fared| matches!(fared, Fared::Panicked(_)));
    let empty = count(|fared| *fared == Fared::Empty);
    let mut out = format!(
        "# Components on Rune\n\nGenerated by `crates/moonframe-rune/src/coverage.rs`: each \
         component's demo or example, rendered headless. It says whether a demo draws, not that it looks \
         or behaves as on GPUI.\n\n{} components: {draws} draw, {partly} draw with a marker, \
         {problem} report a problem, {empty} draw nothing, {panicked} panic.\n\n| Component | Category | Result |\n| --- | --- | --- |\n",
        results.len(),
    );
    for (name, category, fared) in &results {
        let result = match fared {
            Fared::Draws => "draws".to_owned(),
            Fared::Partly(left_out) => {
                let names: Vec<&str> = left_out.iter().map(String::as_str).collect();
                format!("needs {}", names.join(", "))
            },
            Fared::Empty => "draws nothing".to_owned(),
            Fared::Problem(problem) => format!("problem: {}", problem.replace(['|', '\n'], " ")),
            Fared::Panicked(panic) => format!("panic: {}", panic.replace(['|', '\n'], " ")),
        };
        writeln!(out, "| `{name}` | {category} | {result} |").unwrap();
    }
    if let Some(file) = std::env::var_os("MOONFRAME_RUNE_COVERAGE") {
        std::fs::write(file, &out).unwrap();
    }
    println!("{}", out.lines().nth(4).unwrap_or_default());
    assert_eq!(panicked, 0, "{out}");
}
